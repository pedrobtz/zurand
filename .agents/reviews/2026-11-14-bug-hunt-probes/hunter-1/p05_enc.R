source("helper.R")
cat("locale:", Sys.getlocale("LC_CTYPE"), "\n")
k <- rng_key(1L, engine="philox4x64")
F <- function(x) tryCatch(format(rng_fold(k, x)), error=function(e) paste("ERR", conditionMessage(e)))
show <- function(nm, x) cat(sprintf("%-10s enc=%-8s bytes=%-22s fold=%s\n", nm, Encoding(x), paste(charToRaw(x), collapse=" "), F(x)))
u <- "café"; show("u-literal", u)
u2 <- rawToChar(as.raw(c(0x63,0x61,0x66,0xc3,0xa9))); Encoding(u2) <- "UTF-8"; show("u-marked", u2)
l <- rawToChar(as.raw(c(0x63,0x61,0x66,0xe9))); Encoding(l) <- "latin1"; show("l-marked", l)
n1 <- rawToChar(as.raw(c(0x63,0x61,0x66,0xe9))); show("unk e9", n1)
n2 <- rawToChar(as.raw(c(0x63,0x61,0x66,0xc3,0xa9))); show("unk c3a9", n2)
show("enc2utf8(l)", enc2utf8(l))
show("ascii", "cafe")

zc_key_get <- function(keys, i = 0) .Call(C_zc_key_get, keys, as.double(i))
# key: list(k0 = hex, k1 = hex, engine = int, stream = int)
zc_fill <- function(key, n, what, a = 0, b = 1, method = 0L, imin = 0L, imax = 0L)
  .Call(C_zc_fill, key, as.double(n), as.integer(what), as.double(a), as.double(b), as.integer(method), as.integer(imin), as.integer(imax))
zc_fill_at <- function(key, start, n, dist, a = 0, b = 1, method = 0L)
  .Call(C_zc_fill_at, key, as.character(start), as.double(n), as.integer(dist), as.double(a), as.double(b), as.integer(method))
zc_stream <- function(key, total, chunk, dist, a = 0, b = 1, method = 0L, stop_after = 0L, keep = 1e6)
  .Call(C_zc_stream, key, as.character(total), as.double(chunk), as.integer(dist), as.double(a), as.double(b), as.integer(method), as.integer(stop_after), as.double(keep))
zc_fold <- function(key, data) .Call(C_zc_fold, key, as.character(data))
zc_null <- function(key) .Call(C_zc_null, key)
zc_par <- function(key, start, n, pieces, dist, method = 0L, threads = 4L)
  .Call(C_zc_par, key, as.character(start), as.double(n), as.integer(pieces), as.integer(dist), as.integer(method), as.integer(threads))
